"""Hardware dry-run integration of feature loss and PX4 EKF position feedback.

Live output remains unavailable until hardware reference validation is complete.
No simulated observations or fault injections are generated by this adapter.
"""
import math
import time
from boom_birds_control.landing_ekf_reference import LandingEkfReference
from boom_birds_control.landing_ekf_projection import EkfLandingProjection, FeatureWorldSample
from boom_birds_control.landing_ekf_height import LandingEkfHeight
from boom_birds_bringup.lifecycle import State
from boom_birds_bringup.tag_flight_task import LandingFix


class DryRunFeatureEkfBridge:
    def __init__(self, mission, control, reader, *, max_accuracy_m=.2):
        self.mission,self.control,self.reader = mission,control,reader
        self.assertDryRun()
        if mission.handover:
            raise ValueError("ekf_candidate_requires_handover_disabled")
        if type(max_accuracy_m) not in (int,float) or not math.isfinite(max_accuracy_m) or max_accuracy_m <= 0:
            raise ValueError("ekf_accuracy_limit")
        self.maxAccuracy = float(max_accuracy_m)
        self.projection = self.newProjection()
        self.heightReference = LandingEkfHeight(max_age_s=.2,max_pair_skew_s=.08,
            max_accuracy_m=self.maxAccuracy,max_duration_s=12.,max_speed_m_s=1.,max_height_m=5.)
        self.lastHeight = self.lastHeightAt = self.lastEkf = self.worldZAnchor = None
        self.mode = "visual"
        self.last = self.lastSeed = self.lastGround = None
        self.switches = self.ekfTicks = self.outputs = 0
        self.reason = "visual"
        self.seedFailures = {}
        self.originalLandingInputs = mission.landingInputs
        mission.landingInputs = self.landingInputs
        self.originalEvaluate = mission.featureFix.evaluate
        self.originalOutput = control.core.outputHandler
        self.originalPublish = control._publishExecution
        mission.featureFix.evaluate = self.evaluate
        control.core.outputHandler = self.output
        control._publishExecution = self.publish

    def assertDryRun(self):
        if (getattr(self.control.backend,"dry_run",False) is not True
                or self.mission.get_parameter("dry_run").value is not True
                or self.mission.get_parameter("start").value is not False):
            raise ValueError("hardware_ekf_live_not_verified")

    def newProjection(self):
        return EkfLandingProjection(LandingEkfReference(
            max_age_s=.2, max_pair_skew_s=.08, max_accuracy_m=self.maxAccuracy,
            max_duration_s=12., max_displacement_m=.5, max_speed_m_s=1.))

    def landingInputs(self, now):
        if self.mode != "ekf":
            return self.originalLandingInputs(now)
        tracker = self.mission.tracker
        rosNow = self.mission.rosNow()
        ok = (self.last is not None and 0 <= now-self.last.stamp <= .2
              and self.lastHeight is not None and self.lastHeightAt is not None
              and 0 <= now-self.lastHeightAt <= .2)
        self.mission.inputReason = "" if ok else "ekf_height_stale"
        return ok

    def updateHeight(self, now, rosNow, data):
        if data is None:
            return None
        sample = data[0]
        tracker = self.mission.tracker
        reading = None
        if tracker.ranges and tracker.poses:
            rangeStamp, distance = tracker.ranges[-1]
            poseStamp, _, rotation = tracker.poses[-1]
            g = tracker.profile["guidance"]
            if (0 <= rosNow-rangeStamp <= g["range_timeout_s"]
                    and 0 <= rosNow-poseStamp <= g["telemetry_timeout_s"]
                    and g["range_min_m"] <= distance <= g["range_max_m"]
                    and rotation[2,2] >= math.cos(g["max_tilt_rad"])):
                h = -float((rotation @ (tracker.rangeMount[:3,3]
                          +tracker.rangeMount[:3,2]*distance))[2])
                stamp = now-(rosNow-rangeStamp)
                if math.isfinite(h) and h > 0 and abs(stamp-sample.stamp) <= .08:
                    reading = (stamp,h)
                else:
                    # Wait for a time-matched pair, without inventing a sensor loss.
                    return self.lastHeight
        if self.heightReference.anchor is None and reading is None:
            return None
        result = self.heightReference.step(now,sample,
            None if reading is None else reading[0],None if reading is None else reading[1])
        if result is not None:
            self.lastHeight,self.lastHeightAt = result,sample.stamp
        else:
            self.lastHeight = self.lastHeightAt = None
        return result

    def evaluate(self, rosNow):
        self.assertDryRun()
        now = time.monotonic()
        visual = self.originalEvaluate(rosNow)
        fsm = self.mission.fsm
        if fsm.phase == "PX4_FINAL_LAND":
            # PX4 owns final landing; do not reinterpret landed EKF flags as a control failure.
            return None
        airborne = fsm.state in (State.EXECUTING, State.LANDING)
        if not airborne:
            return visual
        data = self.reader.snapshot()
        height = self.updateHeight(now,rosNow,data)
        vio = self.control._vioFeedback
        if self.mode == "visual" and visual is not None and data is not None and vio is not None:
            p, _, _, vioStamp = vio
            offset = self.control.attitude_controller.offset
            stamp = now-(rosNow-visual.stamp)
            if offset is not None and 0 <= now-stamp <= .2:
                sample = FeatureWorldSample(stamp,vioStamp,tuple(visual.target[:2]),
                                            tuple(p[:2]),float(offset))
                # Failed pairing is not a switch; only a successful pairing may seed.
                trial = self.newProjection()
                candidate = trial.step(now,sample,data[0],data[1])
                if candidate is not None and data[0].vertical_position_valid:
                    self.projection = trial
                    self.last, self.lastSeed, self.lastGround = candidate, stamp, visual.target[2]
                    self.worldZAnchor = (float(p[2]),data[0].position_ned_z)
                else:
                    self.seedFailures[trial.reason] = self.seedFailures.get(trial.reason,0)+1
        if (self.mode == "visual" and visual is None and fsm.state == State.LANDING
                and fsm.phase == "TAG_DESCEND"):
            self.mode = "ekf"
            self.switches += 1
        if self.mode == "failed":
            return None
        if self.mode != "ekf":
            return visual
        if (self.lastSeed is None or not 0 <= now-self.lastSeed <= .2
                and self.ekfTicks == 0 or data is None):
            self.mode, self.reason, self.last = "failed", "ekf_anchor_or_sample_missing", None
            return None
        result = self.projection.step(now,None,data[0],data[1])
        if result is None:
            self.mode, self.reason, self.last = "failed", self.projection.reason, None
            return None
        self.last, self.reason = result, "ekf"
        self.lastEkf = data[0]
        self.ekfTicks += 1
        if height is None or self.lastGround is None or self.worldZAnchor is None:
            self.mode,self.reason,self.last = "failed","ekf_height_unavailable",None
            return None
        return LandingFix(rosNow, (*result.target_world_xy,float(self.lastGround)),
                          height, "ekf", rosNow, True, ())

    def feedback(self):
        self.assertDryRun()
        if self.mode == "visual":
            return self.control._vioFeedback
        if self.mode != "ekf" or self.last is None or not 0 <= time.monotonic()-self.last.stamp <= .2:
            raise ValueError("ekf_fallback_unavailable")
        vio = self.control._vioFeedback
        if vio is None or not 0 <= time.monotonic()-vio[3] <= .2:
            raise ValueError("ekf_fallback_vertical_or_attitude_missing")
        p,v,q,stamp = vio
        if (self.lastEkf is None or self.worldZAnchor is None
                or not self.lastEkf.vertical_position_valid
                or self.lastHeight is None or self.lastHeightAt is None
                or not 0 <= time.monotonic()-self.lastHeightAt <= .2):
            raise ValueError("ekf_fallback_vertical_unavailable")
        z = self.worldZAnchor[0]-(self.lastEkf.position_ned_z-self.worldZAnchor[1])
        return ((*self.last.position_world_xy,z),
                (*self.last.velocity_world_xy,-self.lastEkf.velocity_ned_z),q,
                min(stamp,self.last.stamp,self.lastHeightAt))

    def output(self, desired):
        original = self.control._vioFeedback
        try:
            self.control._vioFeedback = self.feedback()
            result = self.originalOutput(desired)
            if self.mode == "ekf" and result:
                self.outputs += 1
            return result
        finally:
            self.control._vioFeedback = original

    def publish(self, outcome):
        original = self.control._vioFeedback
        try:
            try:
                self.control._vioFeedback = self.feedback()
            except ValueError:
                self.control._vioFeedback = None
            self.originalPublish(outcome)
        finally:
            self.control._vioFeedback = original

    def report(self):
        return dict(mode=self.mode,reason=self.reason,switches=self.switches,
                    ekf_ticks=self.ekfTicks,dry_run_outputs=self.outputs,
                    max_accuracy_m=self.maxAccuracy,
                    height_source=self.heightReference.mode,
                    height_reason=self.heightReference.reason,
                    seed_failures=self.seedFailures,live_control_enabled=False)
